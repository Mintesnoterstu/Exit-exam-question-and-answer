def _parse_table(text: str) -> dict[int, str]:
    out = {}
    for line in text.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("|") and "Q#" in line:
            continue
        if "|" not in line:
            continue
        parts = [p.strip() for p in line.split("|") if p.strip()]
        for i in range(0, len(parts) - 1, 2):
            try:
                q = int(parts[i])
                ans = parts[i + 1].lower().strip()
                if ans in "abcd":
                    out[q] = ans
            except ValueError:
                continue
    return out


